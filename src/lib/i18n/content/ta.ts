    if (daysBefore === 0) {
      if (!ctx.deityName) return `${ctx.significance} 🙏`;
      return `${ctx.honorific} ${ctx.deityName} உங்களுக்கும் உங்கள் குடும்பத்துக்கும் வலிமை, ஞானம், அருள் வழங்கட்டும். 🙏`;
    }
